"""
models/forecast_result.py — SQLAlchemy ORM model for the forecast_results table.

Stores future sentiment predictions generated by the forecasting pipeline.
"""

import uuid
from datetime import datetime

from sqlalchemy import Column, Date, DateTime, Float, String, text
from sqlalchemy.dialects.postgresql import UUID

from app.database import Base


class ForecastResult(Base):
    __tablename__ = "forecast_results"

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        nullable=False,
    )
    
    # The date this forecast predicts.
    # Using Date instead of DateTime because forecasts are aggregated daily.
    forecast_date = Column(Date, nullable=False, index=True)
    
    # Predicted sentiment index.
    predicted_sentiment = Column(Float, nullable=False)
    
    # E.g. "prophet"
    model_name = Column(String(128), nullable=False, default="prophet")
    
    # When this forecast was generated by the worker.
    generated_at = Column(
        DateTime(timezone=True),
        server_default=text("NOW()"),
        nullable=False,
        index=True,
    )

    def __repr__(self) -> str:
        return (
            f"<ForecastResult date={self.forecast_date} "
            f"predicted={self.predicted_sentiment:.3f} model={self.model_name}>"
        )
